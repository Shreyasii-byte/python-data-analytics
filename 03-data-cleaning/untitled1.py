import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

import warnings
warnings.filterwarnings("ignore")

sns.set_theme(style="whitegrid")

print("Libraries imported successfully!")

data = {
    "Customer_ID": [101, 102, 103, 104, 105, 106, 107, 108, 108],
    "Name": [
        "Aarav", "riya", "KABIR", "Ananya", "Ishaan",
        "Meera", "Arjun", "Sara", "Sara"
    ],
    "City": [
        "Delhi", "mumbai", "DELHI", None, "Pune",
        "Mumbai", "delhi", "Noida", "Noida"
    ],
    "Age": [25, 30, 28, np.nan, 35, 200, 27, 32, 32],
    "Salary": [55000, 42000, 60000, 75000, np.nan, 45000, 65000, 80000, 80000],
    "Purchase_Amount": [2500, 1800, 3200, 4500, 3500, np.nan, 5800, 2700, 2700],
    "Category": [
        "Electronics", "Clothing", "electronics",
        "Furniture", "Clothing", "Electronics",
        "Furniture", "clothing", "clothing"
    ]
}

df = pd.DataFrame(data)

display(df)

print("Dataset shape:", df.shape)

print("\nDataset information:")
df.info()

print("\nMissing values:")
display(df.isnull().sum())

print("\nDuplicate records:", df.duplicated().sum())

print("\nStatistical summary:")
display(df.describe())

print("Before removing duplicates:", df.shape)

df = df.drop_duplicates()

print("After removing duplicates:", df.shape)

print("Remaining duplicates:", df.duplicated().sum())

# Fill missing numerical values with median
df["Age"] = df["Age"].fillna(df["Age"].median())

df["Salary"] = df["Salary"].fillna(df["Salary"].median())

df["Purchase_Amount"] = df["Purchase_Amount"].fillna(
    df["Purchase_Amount"].median()
)

# Fill missing categorical values with mode
df["City"] = df["City"].fillna(df["City"].mode()[0])

print("Missing values after treatment:")
display(df.isnull().sum())

# Standardize names
df["Name"] = df["Name"].str.strip().str.title()

# Standardize cities
df["City"] = df["City"].str.strip().str.title()

# Standardize categories
df["Category"] = df["Category"].str.strip().str.title()

display(df)

Q1 = df["Age"].quantile(0.25)
Q3 = df["Age"].quantile(0.75)

IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

outliers = df[
    (df["Age"] < lower_bound) |
    (df["Age"] > upper_bound)
]

print("Detected age outliers:")
display(outliers[["Name", "Age"]])

# Remove implausible ages for this illustrative customer dataset
df = df[df["Age"].between(18, 100)].copy()

print("Dataset shape after age validation:", df.shape)

df["Customer_ID"] = df["Customer_ID"].astype(int)

df["Age"] = df["Age"].astype(int)

df["Salary"] = pd.to_numeric(df["Salary"], errors="coerce")

df["Purchase_Amount"] = pd.to_numeric(
    df["Purchase_Amount"], errors="coerce"
)

print("Updated data types:")
print(df.dtypes)

# Check for invalid values
print("Invalid ages:", (~df["Age"].between(18, 100)).sum())

print("Negative salaries:", (df["Salary"] < 0).sum())

print(
    "Negative purchase amounts:",
    (df["Purchase_Amount"] < 0).sum()
)

# Keep valid non-negative monetary values
df = df[
    (df["Salary"] >= 0) &
    (df["Purchase_Amount"] >= 0)
].copy()

print("Validation completed!")

# Calculate annual salary category
df["Salary_Level"] = np.where(
    df["Salary"] >= 60000,
    "High Salary",
    "Standard Salary"
)

# Calculate purchase tax estimate (10%)
df["Estimated_Tax"] = df["Purchase_Amount"] * 0.10

# Calculate total amount
df["Total_Amount"] = (
    df["Purchase_Amount"] + df["Estimated_Tax"]
)

display(df)

fig, axes = plt.subplots(1, 2, figsize=(12, 5))

axes[0].bar(
    ["Before Cleaning", "After Cleaning"],
    [9, len(df)]
)

axes[0].set_title("Number of Records")
axes[0].set_ylabel("Records")

df["Salary"].plot(
    kind="box",
    ax=axes[1]
)

axes[1].set_title("Salary Distribution After Cleaning")

plt.tight_layout()
plt.show()

print("========== FINAL DATA QUALITY REPORT ==========")

print("Final dataset shape:", df.shape)

print("Missing values:", df.isnull().sum().sum())

print("Duplicate rows:", df.duplicated().sum())

print("\nFinal dataset:")
display(df)

print("\nFinal statistical summary:")
display(df.describe())

df.to_csv("cleaned_customer_data.csv", index=False)

print("Cleaned dataset exported successfully!")

