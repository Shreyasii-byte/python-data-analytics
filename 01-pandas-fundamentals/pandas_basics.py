import pandas as pd
import numpy as np

print("Pandas version:", pd.__version__)
print("NumPy version:", np.__version__)

data = {
    "Employee_ID": [101, 102, 103, 104, 105, 106, 107, 108],
    "Name": ["Aarav", "Riya", "Kabir", "Ananya", "Ishaan", "Meera", "Arjun", "Sara"],
    "Department": ["IT", "HR", "Finance", "IT", "Marketing", "HR", "Finance", "IT"],
    "Salary": [55000, 42000, 60000, 75000, 48000, 45000, 65000, 80000],
    "Experience": [2, 1, 4, 5, 2, 3, 4, 6],
    "City": ["Delhi", "Mumbai", "Delhi", "Noida", "Pune", "Mumbai", "Delhi", "Noida"]
}

df = pd.DataFrame(data)

display(df)

print("First five rows:")
display(df.head())

print("Last five rows:")
display(df.tail())

print("Dataset shape:", df.shape)

print("\nColumn names:")
print(df.columns.tolist())

print("\nData types:")
print(df.dtypes)

print("\nDataset information:")
df.info()

print("\nStatistical summary:")
display(df.describe())

# Select one column
print("Employee names:")
display(df["Name"])

# Select multiple columns
print("Employee name and salary:")
display(df[["Name", "Salary"]])

# Employees earning more than 50,000
high_salary = df[df["Salary"] > 50000]

display(high_salary)

# Employees working in IT
it_employees = df[df["Department"] == "IT"]

display(it_employees)

# Employees with more than 3 years of experience
experienced_employees = df[df["Experience"] > 3]

display(experienced_employees)

# Sort by salary in descending order
salary_sorted = df.sort_values(
    by="Salary",
    ascending=False
)

display(salary_sorted)

# Sort by experience
experience_sorted = df.sort_values(
    by="Experience",
    ascending=True
)

display(experience_sorted)

# Average salary by department
department_salary = df.groupby("Department")["Salary"].mean()

display(department_salary)

# Employee count by department
department_count = df.groupby("Department")["Employee_ID"].count()

display(department_count)

# Multiple aggregations
summary = df.groupby("Department").agg(
    Average_Salary=("Salary", "mean"),
    Maximum_Salary=("Salary", "max"),
    Minimum_Salary=("Salary", "min"),
    Employee_Count=("Employee_ID", "count")
)

display(summary)

# Create a copy with missing values
df_missing = df.copy()

df_missing.loc[1, "Salary"] = np.nan
df_missing.loc[4, "City"] = np.nan

print("Missing values before cleaning:")
display(df_missing.isnull().sum())

# Fill missing salary with median
df_missing["Salary"] = df_missing["Salary"].fillna(
    df_missing["Salary"].median()
)

# Fill missing city
df_missing["City"] = df_missing["City"].fillna("Unknown")

print("Missing values after cleaning:")
display(df_missing.isnull().sum())

display(df_missing)

salaries = df["Salary"].to_numpy()

print("Total salary:", np.sum(salaries))
print("Average salary:", np.mean(salaries))
print("Median salary:", np.median(salaries))
print("Maximum salary:", np.max(salaries))
print("Minimum salary:", np.min(salaries))
print("Standard deviation:", np.std(salaries))

# Annual salary is already represented by Salary
# Calculate a 10% estimated annual bonus

df["Bonus"] = df["Salary"] * 0.10

# Calculate total compensation
df["Total_Compensation"] = df["Salary"] + df["Bonus"]

display(df)

highest_paid = df.loc[df["Salary"].idxmax()]
lowest_paid = df.loc[df["Salary"].idxmin()]

print("========== EMPLOYEE ANALYSIS ==========")

print("Total employees:", len(df))
print("Average salary:", round(df["Salary"].mean(), 2))

print(
    "Highest paid employee:",
    highest_paid["Name"],
    "-",
    highest_paid["Salary"]
)

print(
    "Lowest paid employee:",
    lowest_paid["Name"],
    "-",
    lowest_paid["Salary"]
)

print(
    "Department with most employees:",
    df["Department"].value_counts().idxmax()
)

print(
    "Department with highest average salary:",
    df.groupby("Department")["Salary"].mean().idxmax()
)

